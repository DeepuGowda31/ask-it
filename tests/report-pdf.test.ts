import { inflateSync } from 'node:zlib';
import { describe, expect, it } from 'vitest';
import { PDFArray, PDFDocument, PDFName, PDFRawStream, type PDFPage } from 'pdf-lib';
import { buildReportData, type ReportInput } from '@/lib/domain/report';
import { seedBacklog } from '@/lib/domain/desk-seed';
import { DAY, MINUTE } from '@/lib/domain/time';
import type { DeskIncident } from '@/lib/integrations/types';
import { renderReportPdf } from '@/lib/server/report-pdf';
import { NOW } from './helpers';

const OPEN: DeskIncident[] = seedBacklog(NOW).map(({ notes: _notes, ...i }) => i);
const BASE: ReportInput = { period: 'last_7_days', now: NOW, open: [], openMore: false, opened: [], resolved: [], resolvedMore: false, roster: [], notes: {}, source: { mode: 'live', host: 'acme.servicenow.example' } };
const FORBIDDEN = ['pdf-lib', 'pdflib', 'AI-generated', 'Generated by', 'generated by'];

// cp1252 bytes the reports use beyond ASCII.
const CP1252: Record<number, string> = { 0x85: '…', 0xb7: '·', 0x93: '“', 0x94: '”', 0x96: '–', 0x97: '—' };

// Every string drawn on a page, in drawing order, decoded from the content streams.
function pageText(page: PDFPage): string[] {
  const contents = page.node.get(PDFName.of('Contents'));
  const refs = contents instanceof PDFArray ? contents.asArray() : [contents];
  const out: string[] = [];
  for (const ref of refs) {
    const stream = page.doc.context.lookup(ref);
    if (!(stream instanceof PDFRawStream)) continue;
    const raw = Buffer.from(inflateSync(stream.contents)).toString('latin1');
    for (const m of raw.matchAll(/<([0-9A-Fa-f]*)>\s*Tj/g)) {
      const bytes = m[1].match(/../g) ?? [];
      out.push(bytes.map((h) => CP1252[parseInt(h, 16)] ?? String.fromCharCode(parseInt(h, 16))).join(''));
    }
  }
  return out;
}

async function render(o: Partial<ReportInput> = {}) {
  const bytes = await renderReportPdf(buildReportData({ ...BASE, ...o }));
  const doc = await PDFDocument.load(bytes, { updateMetadata: false });
  const pages = doc.getPages().map(pageText);
  return { bytes, doc, pages, text: pages.flat().join('\n') };
}

const many = (n: number): DeskIncident[] =>
  Array.from({ length: n }, (_, k) => ({ ...OPEN[k % OPEN.length], number: `INC00${20000 + k}`, sysId: `s${k}`, summary: `Laptop ${k} cannot reach the file share in the office`, openedAt: NOW - (k + 1) * 3 * 60 * MINUTE }));

describe('renderReportPdf', () => {
  it('is a valid A4 PDF that loads back, with its own metadata only', async () => {
    const { bytes, doc } = await render({ open: OPEN });
    expect(Buffer.from(bytes.slice(0, 5)).toString()).toBe('%PDF-');
    const { width, height } = doc.getPage(0).getSize();
    expect([Math.round(width), Math.round(height)]).toEqual([595, 842]);
    expect(doc.getTitle()).toBe('Weekly IT Service Desk Report');
    expect(doc.getAuthor()).toBe('ASK IT');
    expect(doc.getSubject()).toBe('Last 7 days, 12 to 18 November 2026');
    expect(doc.getCreator()).toBe('ASK IT');
    expect(doc.getProducer()).toBe('ASK IT');
    expect(doc.getCreationDate()?.getTime()).toBe(Math.floor(NOW / 1000) * 1000);
  });
  it('never names the tools that made it, in the bytes or on the page', async () => {
    const { bytes, text } = await render({ open: OPEN });
    const raw = Buffer.from(bytes).toString('latin1');
    for (const s of FORBIDDEN) {
      expect(raw).not.toContain(s);
      expect(text).not.toContain(s);
    }
    expect(text).not.toMatch(/\bAI\b|model/i);
  });
  it('lays out every section, with page numbers, and no colons, semicolons or dashes in its own words', async () => {
    const notes = { INC0013006: { at: NOW - DAY, author: 'david.loo', text: 'Replacement battery ordered from the vendor' } };
    const resolved = [{ ...OPEN[1], number: 'INC0012999', state: '6', stateLabel: 'Resolved', openedAt: NOW - 5 * 60 * MINUTE, resolvedAt: NOW - 60 * MINUTE }];
    const { pages, text } = await render({ open: OPEN, opened: OPEN.map((i) => i.openedAt!), resolved, notes });
    for (const heading of ['Weekly IT Service Desk Report', 'Last 7 days · 12 to 18 November 2026', 'Prepared 18 November 2026 at 9.30 AM India time', 'Live from ServiceNow, acme.servicenow.example', 'Key figures', 'Open by priority', 'Open by state', 'Open by team', 'New and resolved per day', 'Needs attention', 'Critical and high priority', 'On hold', 'Unassigned', 'Resolved in the period', 'Team workload', 'All open incidents']) {
      expect(text).toContain(heading);
    }
    expect(text).toContain('Replacement battery ordered from the vendor');
    expect(text).toContain('INC0012999');
    expect(text).toContain('4 h');
    pages.forEach((p, n) => expect(p).toContain(`Page ${n + 1} of ${pages.length}`));
    // Titles are data; the rest is the report's own copy.
    const titles = new Set([...OPEN.map((i) => i.summary)]);
    const isTitle = (line: string) => titles.has(line) || (line.endsWith('…') && [...titles].some((t) => t.startsWith(line.slice(0, -1))));
    for (const line of pages.flat()) if (!isTitle(line)) expect(line, line).not.toMatch(/[;:\-–—]/);
  });
  it('says None in one line for empty sections instead of empty tables', async () => {
    const { text, pages } = await render();
    expect(pages.length).toBeLessThanOrEqual(2);
    expect(text.split('\n').filter((l) => l === 'None').length).toBeGreaterThanOrEqual(6);
    expect(text.split('\n')).not.toContain('INCIDENT');
  });
  it('grows by pages for long queues, repeating the table header on each', async () => {
    const small = await render({ open: OPEN });
    const big = await render({ open: many(160) });
    expect(big.pages.length).toBeGreaterThan(small.pages.length + 2);
    const withTable = big.pages.filter((p) => p.some((l) => l.startsWith('All open incidents')));
    expect(withTable.length).toBeGreaterThan(2);
    for (const p of withTable) expect(p).toContain('INCIDENT');
    for (let k = 0; k < 160; k++) expect(big.text).toContain(`INC00${20000 + k}`);
  });
  it('truncates long titles inside their column and replaces characters the font cannot draw', async () => {
    const long = { ...OPEN[0], summary: `Very long title ${'about the shared drive '.repeat(10)}end` };
    const odd = { ...OPEN[1], number: 'INC0013999', summary: 'Café printer ✓ 数据 “quoted”' };
    const { text } = await render({ open: [long, odd] });
    expect(text).not.toContain('shared drive end');
    expect(text).toMatch(/Very long title about the[^\n]*…/);
    expect(text).toContain('Café printer ? ?? “quoted”');
  });
});
